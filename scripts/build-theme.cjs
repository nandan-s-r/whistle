// Rebuild the dark colour layer from the existing light palette. Dimensions and
// fixed charcoal navigation/assistant surfaces stay in the original stylesheets.
const fs = require('node:fs');
const path = require('node:path');
const postcss = require('../frontend/node_modules/postcss');
const app = path.resolve(__dirname, '../frontend/src/app');
const output = postcss.root();
const fixed = /research-sidebar|research-nav|sidebar-|scope-brand|brand-symbol|brand-os|workspace-identity|workspace-dot|workspace-monogram|auth-story|auth-pitch|auth-journey|assistant-drawer/;
const semantic = { '#0f766e': 'verified', '#b45309': 'warning', '#b91c1c': 'risk', '#6d28d9': 'ai' };

function token(colour, property) {
  const lower = colour.toLowerCase();
  if (lower.length !== 4 && lower.length !== 7) return colour;
  const hex = lower.length === 4 ? lower.slice(1).split('').map(x => x+x).join('') : lower.slice(1);
  const [r,g,b] = [0,2,4].map(i => parseInt(hex.slice(i,i+2),16));
  const text = ['color','fill','stroke','caret-color','outline','outline-color'].includes(property);
  if (text) {
    if (semantic[lower]) return `var(--theme-${semantic[lower]})`;
    if (['#2563eb','#1d4ed8','#3b82f6'].includes(lower)) return 'var(--theme-link)';
    if (['#0b1220','#132a4a','#14263f','#253d5c','#263448','#244362'].includes(lower)) return 'var(--theme-text)';
    if (Math.max(r,g,b) < 175) return 'var(--theme-muted)';
    return colour;
  }
  if (!/background|border/.test(property) || Math.min(r,g,b) < 175) return colour;
  if (/border/.test(property)) return 'var(--theme-border)';
  if (r >= 250 && g >= 250 && b >= 250) return 'var(--theme-surface)';
  if (g > r + 8 && g >= b) return 'var(--theme-verified-soft)';
  if (r > b + 12 && r > g + 5) return g > b + 10 ? 'var(--theme-warning-soft)' : 'var(--theme-risk-soft)';
  if (b > g + 8 && r > g + 5) return 'var(--theme-ai-soft)';
  if (b > r + 10) return 'var(--theme-accent-soft)';
  return 'var(--theme-raised)';
}

function collect(node, destination) {
  if (node.type === 'atrule') {
    if (!['media','supports'].includes(node.name)) return;
    const wrapper = node.clone({nodes: []});
    for (const child of node.nodes ?? []) collect(child, wrapper);
    if (wrapper.nodes.length) destination.append(wrapper);
  } else if (node.type === 'rule') {
    const selectors = node.selectors.filter(selector => !fixed.test(selector));
    if (!selectors.length) return;
    const rule = postcss.rule({selector: selectors.map(selector => `html[data-theme="dark"] ${selector}`).join(',\n')});
    for (const declaration of node.nodes) {
      if (declaration.type !== 'decl' || declaration.prop.startsWith('--')) continue;
      const value = declaration.value.replace(/#[0-9a-f]{3,8}\b/gi, colour => token(colour, declaration.prop));
      if (value !== declaration.value) rule.append(declaration.clone({value}));
    }
    if (rule.nodes?.length) destination.append(rule);
  }
}

for (const file of ['workspace.css','research-ui.css','experience-ui.css','decision-ui.css','studio-ui.css','brand-ui.css','risk-ui.css','ecosystem-ui.css']) {
  const source = postcss.parse(fs.readFileSync(path.join(app,file),'utf8'));
  for (const node of source.nodes) collect(node, output);
}
const base = fs.readFileSync(path.join(app,'theme-tokens.css'),'utf8');
fs.writeFileSync(path.join(app,'theme.css'), `${base}\n/* Generated by scripts/build-theme.cjs; edit the source palette or theme-tokens.css. */\n${output.toString()}\n`);
console.log('Dark theme generated from the workspace palette.');
